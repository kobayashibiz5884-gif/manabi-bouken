  function toKata(s) {
    return s.replace(/[ぁ-ゖ]/g, function (c) { return String.fromCharCode(c.charCodeAt(0) + 0x60); });
  }
  function toHira(s) {
    return s.replace(/[ァ-ヶ]/g, function (c) { return String.fromCharCode(c.charCodeAt(0) - 0x60); });
  }

  // script: 'hira' | 'kata'
  function makeSet(script) {
    var conv = script === 'kata' ? toKata : function (s) { return s; };
    var items = {}, order = [];
    LETTERS.forEach(function (l) {
      var ch = conv(l[0]);
      items[ch] = { ch: ch, sound: toKata(l[0]), word: l[1], wordSay: toKata(l[1]), emoji: l[2] };
      order.push(ch);
    });
    // 特別な読み上げ
    var wo = conv('を'), n = conv('ん');
    items[wo].sound = 'オ'; items[wo].hintSay = 'くっつきの、オ'; items[wo].hintEmoji = '🔗';
    items[n].sound = 'ン'; items[n].hintSay = 'おしまいの、ン'; items[n].hintEmoji = '🔚';
    var sim = {};
    (script === 'kata' ? SIMILAR_K : SIMILAR_H).forEach(function (p) {
      var a = p[0], b = p[1];
      (sim[a] = sim[a] || []).push(b);
      (sim[b] = sim[b] || []).push(a);
    });
    var same = {};
    SAME_SOUND.forEach(function (p) { same[p[0]] = p[1]; same[p[1]] = p[0]; });
    var words = WORDS.map(function (w) { return { w: conv(w[0]), say: toKata(w[0]), emoji: w[1] }; });
    return { script: script, items: items, order: order, similar: sim, same: same, words: words };
  }

  // 名前の文字から、最初に覚える文字を選ぶ。 nameKana: ひらがなの名前。 返り値: 最初の5文字（ひらがな）
  function firstLetters(nameKana, count) {
    count = count || 5;
    var set = makeSet('hira');
    var out = [];
    toHira(nameKana || '').split('').forEach(function (c) {
      if (set.items[c] && out.indexOf(c) < 0 && out.length < count) out.push(c);
    });
    // 足りない分は あいうえお順 から、すでに選んだ文字と形が似ていないものを足す
    for (var i = 0; i < set.order.length && out.length < count; i++) {
      var c = set.order[i];
      if (out.indexOf(c) >= 0) continue;
      var clash = out.some(function (o) { return (set.similar[o] || []).indexOf(c) >= 0 || set.same[o] === c; });
      if (!clash) out.push(c);
    }
    return out;
  }

